package com.migal.smartops.comun.errores;

import org.springframework.http.HttpStatus;

/**
 * Catálogo de códigos de error de negocio del contrato de la API (ADR-006, ADR-008 y ADR-009). Cada
 * código tiene un estado HTTP asociado y su nombre es estable entre versiones.
 */
public enum CodigoError {

	NO_AUTENTICADO(HttpStatus.UNAUTHORIZED),
	PERMISO_INSUFICIENTE(HttpStatus.FORBIDDEN),
	RECURSO_NO_ENCONTRADO(HttpStatus.NOT_FOUND),
	SOLICITUD_MAL_FORMADA(HttpStatus.BAD_REQUEST),
	VALIDACION_FALLIDA(HttpStatus.UNPROCESSABLE_ENTITY),
	SKU_DUPLICADO(HttpStatus.CONFLICT),
	RUC_DUPLICADO(HttpStatus.CONFLICT),
	DOCUMENTO_CLIENTE_DUPLICADO(HttpStatus.CONFLICT),
	USUARIO_DUPLICADO(HttpStatus.CONFLICT),
	CLIENTE_INACTIVO(HttpStatus.UNPROCESSABLE_ENTITY),
	CLIENTE_REQUERIDO(HttpStatus.UNPROCESSABLE_ENTITY),
	PROVEEDOR_INACTIVO(HttpStatus.UNPROCESSABLE_ENTITY),
	STOCK_INSUFICIENTE(HttpStatus.CONFLICT),
	VIABILIDAD_NO_CONFIRMADA(HttpStatus.CONFLICT),
	COTIZACION_NO_EDITABLE(HttpStatus.CONFLICT),
	COTIZACION_VENCIDA(HttpStatus.CONFLICT),
	COTIZACION_NO_CONVERTIBLE(HttpStatus.CONFLICT),
	COTIZACION_YA_CONVERTIDA(HttpStatus.CONFLICT),
	VENTA_NO_CANCELABLE(HttpStatus.CONFLICT),
	VENTA_NO_DESPACHABLE(HttpStatus.CONFLICT),
	GUIA_EXISTENTE(HttpStatus.CONFLICT),
	RESERVA_INCOMPLETA(HttpStatus.CONFLICT),
	SALIDA_NO_CONFIRMABLE(HttpStatus.CONFLICT),
	ORDEN_COMPRA_CERRADA(HttpStatus.CONFLICT),
	RECEPCION_NO_CONFIRMABLE(HttpStatus.CONFLICT),
	SOBRANTE_SIN_NOTA(HttpStatus.UNPROCESSABLE_ENTITY),
	MOTIVO_REQUERIDO(HttpStatus.UNPROCESSABLE_ENTITY),
	IDEMPOTENCIA_CONFLICTO(HttpStatus.CONFLICT),
	PETICION_CONCURRENTE(HttpStatus.CONFLICT),
	DOCUMENTO_ILEGIBLE(HttpStatus.UNPROCESSABLE_ENTITY),
	DOCUMENTO_NO_VALIDABLE(HttpStatus.CONFLICT),
	SERVICIO_NO_DISPONIBLE(HttpStatus.SERVICE_UNAVAILABLE),
	ERROR_INTERNO(HttpStatus.INTERNAL_SERVER_ERROR),
	CUENTA_INACTIVA(HttpStatus.FORBIDDEN),
	ADMINISTRADOR_REQUERIDO(HttpStatus.CONFLICT),
	CATEGORIA_NO_ENCONTRADA(HttpStatus.UNPROCESSABLE_ENTITY),
	PRODUCTO_INACTIVO(HttpStatus.UNPROCESSABLE_ENTITY),
	ALMACEN_INACTIVO(HttpStatus.UNPROCESSABLE_ENTITY),
	MOVIMIENTO_NO_CORREGIBLE(HttpStatus.CONFLICT),
	TRANSICION_NO_PERMITIDA(HttpStatus.CONFLICT),
	COTIZACION_NO_VENCIDA(HttpStatus.CONFLICT),
	DOCUMENTO_NO_VALIDADO(HttpStatus.CONFLICT);

	private final HttpStatus estado;

	CodigoError(HttpStatus estado) {
		this.estado = estado;
	}

	/** Estado HTTP con el que la API responde este código. */
	public HttpStatus estado() {
		return estado;
	}
}
